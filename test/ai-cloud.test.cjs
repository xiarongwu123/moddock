async function fixture(t) {
 const root = await fs.mkdtemp(path.join(os.tmpdir(), 'ai-cloud-'));
 const filename = path.join(root, 'accounts.sqlite');
 const db = new DatabaseSync(filename);
 db.exec("CREATE TABLE AspNetUsers(Id TEXT PRIMARY KEY); INSERT INTO AspNetUsers VALUES('a'),('b'),('standard'),('expired');"); db.close();
 let now = Date.parse('2026-10-20T00:00:00Z');
 const account = async id => ({ id, membership: { tier: id === 'standard' ? 'standard' : 'pro', expiresAt: id === 'expired' ? '2020-01-01' : null }, features: [{ key: 'library.manage', allowed: true }] });
 const ledger = new AILedger({ filename, account, clock: () => now, lease: 1000 });
 t.after(async () => { ledger.close(); await fs.rm(root, { recursive: true, force: true }); });
 return { root, filename, ledger, account, time: n => now = n };
}
test('live Pro checks, atomic shared reservations, exact settlement and replay across connections', async t => {
 const { ledger, filename, account } = await fixture(t);
 const second = new AILedger({ filename, account, clock: ledger.clock, lease: 1000 }); t.after(() => second.close());
 for (const id of ['standard', 'expired']) await assert.rejects(ledger.reserve(id, 'task', 10), { code: 'pro_required' });
 ledger.quota('a');
 ledger.db.prepare("UPDATE ModdockAiPeriods SET used=980000 WHERE owner='a'").run();
 const reservations = await Promise.allSettled([ledger.reserve('a', 'one', 18000, 2000), second.reserve('a', 'two', 18000, 2000)]);
 assert.equal(reservations.filter(r => r.status === 'fulfilled').length, 1);
 assert.equal(reservations.find(r => r.status === 'rejected').reason.code, 'ai_credits_exhausted');
 const winner = reservations[0].status === 'fulfilled' ? 'one' : 'two', call = reservations.find(r => r.status === 'fulfilled').value;
 assert.equal(ledger.quota('a').reservedTokens, 20000);
 const usage = { inputTokens: 13000, outputTokens: 2000 };
 assert.deepEqual(ledger.settle('a', winner, call.id, usage, 'provider-1'), usage);
 ledger.settle('a', winner, call.id, usage, 'provider-1');
 assert.equal(ledger.quota('a').usedTokens, 995000); assert.equal(ledger.quota('a').reservedTokens, 0);
 assert.equal(ledger.quota('b').usedTokens, 0);
 assert.throws(() => ledger.settle('b', winner, call.id, usage, 'provider-1'), { code: 'invalid_request' });
 const last = await ledger.reserve('a', 'last', 4999, 100);
 assert.equal(last.outputBudget, 1);
 ledger.settle('a', 'last', last.id, { inputTokens: 4999, outputTokens: 1 }, 'last');
 await assert.rejects(ledger.reserve('a', 'blocked', 0, 1), { code: 'ai_credits_exhausted' });
});
test('crash recovery releases reservations, blocks unknown billing, reconciles actual usage into original period', async t => {
 const { ledger, time } = await fixture(t);
 const call = await ledger.reserve('a', 'crash', 100, 100);
 time(Date.parse('2026-11-01T00:00:00Z'));
 assert.equal(ledger.quota('a').reservedTokens, 0); assert.equal(ledger.quota('a').reconciliationRequired, true);
 await assert.rejects(ledger.reserve('a', 'new', 1), { code: 'ai_quota_unconfigured' });
 ledger.settle('a', 'crash', call.id, { inputTokens: 80, outputTokens: 10 }, 'recovered');
 assert.equal(ledger.quota('a').usedTokens, 0); assert.equal(ledger.quota('a').reconciliationRequired, false);
 assert.equal(ledger.db.prepare("SELECT used FROM ModdockAiPeriods WHERE owner='a' AND start LIKE '2026-10%'").get().used, 90);
 assert.equal(ledger.quota('a').periodEnd, '2026-12-01T00:00:00.000Z');
});
test('SIGKILL preserves provider identity and converts a dead worker reservation into reconcilable billing', async t => {
 const { ledger, filename, time } = await fixture(t);
 const code = `const { AILedger } = require(process.argv[2]);
 const ledger = new AILedger({filename:process.argv[1],clock:()=>Date.parse('2026-10-20T00:00:00Z'),lease:1000,
  account:async id=>({id,membership:{tier:'pro',expiresAt:null},features:[{key:'library.manage',allowed:true}]})});
 ledger.reserve('a','killed',100,100).then(call=>{ledger.identify('a','killed',call.id,'provider-killed');process.stdout.write(call.id);setInterval(()=>{},1000)});`;
 const worker = spawn(process.execPath, ['-e', code, filename, path.resolve(__dirname, '../platform/ai-ledger.cjs')], { stdio: ['ignore', 'pipe', 'ignore'] });
 t.after(() => worker.kill('SIGKILL'));
 const [bytes] = await once(worker.stdout, 'data');
 const exited = once(worker, 'exit'); worker.kill('SIGKILL'); await exited;
 const id = bytes.toString();
 assert.equal(ledger.quota('a').reservedTokens, 200);
 time(Date.parse('2026-10-20T00:00:02Z'));
 assert.equal(ledger.quota('a').reservedTokens, 0); assert.equal(ledger.quota('a').reconciliationRequired, true);
 assert.equal(ledger.db.prepare('SELECT provider_id FROM ModdockAiCalls WHERE id=?').get(id).provider_id, 'provider-killed');
 ledger.settle('a', 'killed', id, { inputTokens: 50, outputTokens: 10 }, 'provider-killed');
 assert.equal(ledger.quota('a').usedTokens, 60); assert.equal(ledger.quota('a').reconciliationRequired, false);
});
test('meter wraps the real Pi SDK, clamps provider output, counts cached input once, drains cancel and fails closed without usage', async t => {
 const { ledger } = await fixture(t);
 const { meteredStream } = await import('../platform/ai-meter.mjs');
 const { streamSimple } = await import('../platform/node_modules/@earendil-works/pi-ai/dist/compat.js');
 let received, omitUsage = false, failAfterUsage = false;
 const controller = new AbortController();
 const server = http.createServer(async (req, res) => {
  const chunks = []; for await (const chunk of req) chunks.push(chunk); received = JSON.parse(Buffer.concat(chunks));
  res.writeHead(200, { 'Content-Type': 'text/event-stream' });
  const frame = row => res.write('data: ' + JSON.stringify(row) + '\n\n');
  const base = { id: 'provider-' + Math.random(), object: 'chat.completion.chunk', model: 'test', choices: [] };
  frame({ ...base, choices: [{ index: 0, delta: { content: 'hello' }, finish_reason: null }] });
  controller.abort();
  if (!omitUsage) frame({ ...base, usage: { prompt_tokens: 120, completion_tokens: 30, prompt_cache_hit_tokens: 100 } });
  if (failAfterUsage) setTimeout(() => res.destroy(), 20);
  else { frame({ ...base, choices: [{ index: 0, delta: {}, finish_reason: 'stop' }] }); res.end('data: [DONE]\n\n'); }
 });
 await new Promise(resolve => server.listen(0, '127.0.0.1', resolve)); t.after(() => new Promise(resolve => server.close(resolve)));
 const model = { id: 'test', name: 'test', api: 'openai-completions', provider: 'test', baseUrl: 'http://127.0.0.1:' + server.address().port + '/v1', reasoning: false, input: ['text'], contextWindow: 128000, maxTokens: 16384, cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 } };
 const seen = [];
 const invoke = (task, signal) => meteredStream(streamSimple, { ledger, owner: 'a', task, onUsage: usage => seen.push(usage) })(model, { messages: [{ role: 'user', content: 'hello', timestamp: Date.now() }] }, { apiKey: 'test-key', signal });
 assert.equal((await invoke('normal', controller.signal).result()).stopReason, 'stop');
 assert.equal(received.stream_options.include_usage, true); assert.ok(received.max_tokens <= 16384);
 assert.deepEqual(seen, [{ inputTokens: 120, outputTokens: 30 }]);
 assert.equal(ledger.quota('a').usedTokens, 150); assert.equal(ledger.quota('a').reservedTokens, 0);
 failAfterUsage = true;
 assert.equal((await invoke('failed').result()).stopReason, 'error');
 assert.equal(ledger.quota('a').usedTokens, 300); assert.equal(ledger.quota('a').reservedTokens, 0);
 failAfterUsage = false;
 omitUsage = true;
 assert.equal((await invoke('unknown').result()).stopReason, 'error');
 assert.equal(ledger.quota('a').reconciliationRequired, true);
 assert.equal(ledger.quota('a').usedTokens, 300);
 assert.ok(ledger.db.prepare("SELECT provider_id FROM ModdockAiCalls WHERE task='unknown'").get().provider_id);
});
test('delivery reconnect/restart/ownership and cancellation retain one worker and cumulative usage before error', async t => {
 const { root } = await fixture(t);
 let calls = 0, release;
 const directory = path.join(root, 'tasks');
 const tasks = new StudioTasks({ directory, reserve: () => () => {}, timeout: 2000, execute: async (action, payload) => {
  calls++; await new Promise(resolve => release = resolve);
  await payload.onUsage({ inputTokens: 12, outputTokens: 4 });
  payload.signal.throwIfAborted(); return { done: true };
 } });
 t.after(() => tasks.close());
 const delivery = { version: 1, id: require('node:crypto').randomUUID(), after: 0, operation: 'subscribe' };
 const one = await tasks.obtain('a', 'plan', { prompt: 'x' }, delivery);
 assert.equal(await tasks.obtain('a', 'plan', { prompt: 'x' }, delivery), one);
 await assert.rejects(tasks.obtain('b', 'plan', { prompt: 'x' }, delivery), { code: 'invalid_request' });
 one.cancelled = true; one.controller.abort(); release(); await Promise.all([...tasks.runs]);
 assert.equal(calls, 1); assert.equal(one.frames.at(-2).type, 'usage'); assert.equal(one.frames.at(-1).code, 'studio_cancelled');
 const restarted = new StudioTasks({ directory, reserve: () => { throw new Error('Must not run'); }, execute: () => {} });
 t.after(() => restarted.close());
 const loaded = await restarted.obtain('a', 'plan', { prompt: 'x' }, delivery);
 assert.equal(loaded.frames.at(-2).usage.inputTokens, 12); assert.equal(calls, 1);
});
